import * as XLSX from 'xlsx'
import jsPDF from 'jspdf'
import 'jspdf-autotable'

/**
 * Universal Dealership Reports Export Service
 * Produces enterprise-grade, beautifully structured Excel (.xlsx) workbooks
 * and print-ready, branded PDF documents for Bykelink Motor Inc.
 */

/**
 * Generates the structured Array-of-Arrays (AOA) data, merge coordinates,
 * and column specifications for an enterprise Bykelink Excel report.
 */
export function buildExcelAoaData({
  reportTitle = 'OPERATIONAL AUDIT REPORT',
  subtitle = 'Motorcycle Dealership & Precision Service Center Management System',
  periodText = 'All Records',
  generatedBy = 'Administrator',
  kpis = [], // Array of { label: string, value: string | number }
  columns = [], // Array of { header: string, key: string, wch?: number }
  data = [], // Array of record objects
}) {
  const wsData = []

  // Zone 1: Official Company Header Banner
  wsData.push(['BYKELINK MOTOR INC.'])
  wsData.push([subtitle])
  wsData.push([reportTitle.toUpperCase()])
  wsData.push([
    `Reporting Period: ${periodText}   |   Generated: ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' })}   |   Generated By: ${generatedBy}`,
  ])
  wsData.push([]) // Spacer

  // Zone 2: Executive Summary KPI Cards Block
  if (Array.isArray(kpis) && kpis.length > 0) {
    wsData.push(['EXECUTIVE SUMMARY METRICS'])
    const kpiLabels = []
    const kpiValues = []
    kpis.forEach((kpi) => {
      kpiLabels.push(kpi.label.toUpperCase())
      kpiValues.push(kpi.value)
    })
    wsData.push(kpiLabels)
    wsData.push(kpiValues)
    wsData.push([]) // Spacer
  }

  // Zone 3: Structured Data Table Header
  const tableHeaders = columns.map((col) => col.header)
  wsData.push(tableHeaders)

  // Data rows
  data.forEach((item) => {
    const row = columns.map((col) => {
      const val = item[col.key]
      return val !== undefined && val !== null ? val : '—'
    })
    wsData.push(row)
  })

  // Zone 4: Managerial Audit & Sign-Off Block
  wsData.push([]) // Spacer
  wsData.push(['MANAGERIAL AUDIT & VERIFICATION SIGN-OFF'])
  wsData.push([
    'Prepared By: ___________________________',
    '',
    '',
    'Verified & Approved By: ___________________________',
  ])
  wsData.push([
    `Signature over Printed Name (${generatedBy})`,
    '',
    '',
    'Store Management / Branch Auditor',
  ])
  wsData.push([
    `Date Signed: ${new Date().toLocaleDateString()}`,
    '',
    '',
    'Date Signed: ___________________________',
  ])

  // Configure Merged Banner Headers
  const colCount = Math.max(columns.length - 1, 5)
  const merges = [
    { s: { r: 0, c: 0 }, e: { r: 0, c: colCount } }, // Row 1 Company Name
    { s: { r: 1, c: 0 }, e: { r: 1, c: colCount } }, // Row 2 Subtitle
    { s: { r: 2, c: 0 }, e: { r: 2, c: colCount } }, // Row 3 Title
    { s: { r: 3, c: 0 }, e: { r: 3, c: colCount } }, // Row 4 Metadata
  ]

  if (Array.isArray(kpis) && kpis.length > 0) {
    merges.push(
      { s: { r: 5, c: 0 }, e: { r: 5, c: colCount } }, // Row 6 KPI title
    )
  }

  // Set intelligent column widths
  const cols = columns.map((col) => ({
    wch: col.wch || Math.max(col.header.length + 5, 16),
  }))

  return { wsData, merges, cols }
}

/**
 * Exports data into a highly organized, professional Excel workbook.
 * Features:
 * - Official Bykelink Motor Inc. merged company header banner
 * - Dealership system subtitle and audit metadata
 * - Executive summary KPI metrics block
 * - Clean data table with auto-fitted column widths
 * - Managerial sign-off and audit verification block
 */
export function exportProfessionalExcel({
  filename = 'bykelink-report',
  sheetName = 'Report',
  reportTitle = 'OPERATIONAL AUDIT REPORT',
  subtitle = 'Motorcycle Dealership & Precision Service Center Management System',
  periodText = 'All Records',
  generatedBy = 'Administrator',
  kpis = [], // Array of { label: string, value: string | number }
  columns = [], // Array of { header: string, key: string, wch?: number }
  data = [], // Array of record objects
  writer = XLSX.writeFile,
}) {
  const { wsData, merges, cols } = buildExcelAoaData({
    reportTitle,
    subtitle,
    periodText,
    generatedBy,
    kpis,
    columns,
    data,
  })

  // Convert AOA to Sheet
  const worksheet = XLSX.utils.aoa_to_sheet(wsData)
  worksheet['!merges'] = merges
  worksheet['!cols'] = cols

  // Create workbook and write
  const workbook = XLSX.utils.book_new()
  const safeSheetName = sheetName.replace(/[:\\/?*\[\]]/g, '').slice(0, 31) || 'Report'
  XLSX.utils.book_append_sheet(workbook, worksheet, safeSheetName)

  const dateSlug = new Date().toISOString().split('T')[0]
  const finalFilename = `${filename}-${dateSlug}.xlsx`
  if (typeof writer === 'function') {
    writer(workbook, finalFilename)
  }
  return { workbook, finalFilename }
}

/**
 * Exports data into a print-ready, branded PDF document.
 * Features:
 * - Official Bykelink Crimson banner header (#c51d34)
 * - Metadata & period information
 * - Executive summary KPI cards
 * - AutoTable with alternating row colors
 * - Bottom management sign-off section
 */
export function exportBrandedPdf({
  filename = 'bykelink-report',
  title = 'OPERATIONAL REPORT',
  subtitle = 'Motorcycle Dealership & Precision Service Center Management System',
  periodText = 'All Records',
  generatedBy = 'Administrator',
  kpis = [],
  columns = [],
  data = [],
  orientation = 'landscape',
}) {
  const doc = new jsPDF({ orientation })
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()

  // 1. Bykelink Crimson Brand Header Banner (#c51d34)
  doc.setFillColor(197, 29, 52)
  doc.rect(0, 0, pageWidth, 22, 'F')

  doc.setTextColor(255, 255, 255)
  doc.setFontSize(13)
  doc.setFont('helvetica', 'bold')
  doc.text('BYKELINK MOTOR INC.', 14, 10)

  doc.setFontSize(8)
  doc.setFont('helvetica', 'normal')
  doc.text(subtitle, 14, 16)

  doc.setFontSize(8)
  const nowText = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' })
  doc.text(`Generated: ${nowText}  |  By: ${generatedBy}`, pageWidth - 14, 13, { align: 'right' })

  // 2. Report Title & Period
  doc.setTextColor(30, 30, 30)
  doc.setFontSize(12)
  doc.setFont('helvetica', 'bold')
  doc.text(title.toUpperCase(), 14, 30)

  doc.setFontSize(8)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(110, 110, 110)
  doc.text(`Reporting Scope / Period: ${periodText}`, 14, 35)

  // 3. Executive KPI Tiles
  let startY = 40
  if (Array.isArray(kpis) && kpis.length > 0) {
    const tileSpacing = 4
    const totalPadding = 28 + (kpis.length - 1) * tileSpacing
    const tileWidth = Math.max(30, (pageWidth - totalPadding) / kpis.length)

    kpis.forEach((kpi, idx) => {
      const tileX = 14 + idx * (tileWidth + tileSpacing)

      doc.setFillColor(245, 245, 248)
      doc.setDrawColor(220, 220, 225)
      doc.roundedRect(tileX, startY, tileWidth, 14, 2, 2, 'FD')

      doc.setFontSize(6.5)
      doc.setTextColor(100, 100, 100)
      doc.setFont('helvetica', 'bold')
      doc.text(kpi.label.toUpperCase(), tileX + 3, startY + 4.5)

      doc.setFontSize(9)
      doc.setTextColor(20, 20, 20)
      doc.setFont('helvetica', 'bold')
      doc.text(String(kpi.value), tileX + 3, startY + 10.5)
    })

    startY += 18
  }

  // 4. Data AutoTable
  const head = [columns.map((col) => col.header)]
  const body = data.map((item) => columns.map((col) => (item[col.key] !== undefined && item[col.key] !== null ? item[col.key] : '—')))

  doc.autoTable({
    startY,
    head,
    body,
    theme: 'striped',
    styles: {
      font: 'helvetica',
      fontSize: 7.5,
      cellPadding: 2,
    },
    headStyles: {
      fillColor: [35, 35, 38],
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: 'bold',
      halign: 'left',
    },
    alternateRowStyles: {
      fillColor: [250, 250, 252],
    },
    margin: { left: 14, right: 14 },
    didDrawPage: (pageData) => {
      // Bottom footer page numbers
      doc.setFontSize(7)
      doc.setTextColor(150, 150, 150)
      doc.text(
        `Page ${pageData.pageNumber} of ${doc.internal.getNumberOfPages()}`,
        pageWidth - 14,
        pageHeight - 8,
        { align: 'right' },
      )
    },
  })

  // 5. Managerial Sign-Off Block
  const finalY = doc.lastAutoTable ? doc.lastAutoTable.finalY + 10 : startY + 20
  if (finalY < pageHeight - 25) {
    doc.setFontSize(7.5)
    doc.setTextColor(50, 50, 50)
    doc.setFont('helvetica', 'bold')
    doc.text('Prepared By: ___________________________', 14, finalY)
    doc.text('Verified & Approved By: ___________________________', pageWidth / 2 + 10, finalY)

    doc.setFontSize(6.5)
    doc.setTextColor(120, 120, 120)
    doc.setFont('helvetica', 'normal')
    doc.text(`Name & Signature (${generatedBy})`, 14, finalY + 4.5)
    doc.text('Store Management / Branch Auditor', pageWidth / 2 + 10, finalY + 4.5)

    doc.text(`Date Signed: ${nowText}`, 14, finalY + 9)
    doc.text('Date Signed: ___________________________', pageWidth / 2 + 10, finalY + 9)
  }

  const dateSlug = new Date().toISOString().split('T')[0]
  doc.save(`${filename}-${dateSlug}.pdf`)
}
